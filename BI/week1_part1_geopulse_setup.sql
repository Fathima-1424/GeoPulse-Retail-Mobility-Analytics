INSERT INTO GEOPULSE_DB.RAW.GPS_PINGS
(
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    EVENT_TIMESTAMP,
    LOCATION
)

SELECT
    TRIM(DEVICEID),

    TRY_TO_DOUBLE(LATITUDE),

    TRY_TO_DOUBLE(LONGITUDE),

    TRY_TO_TIMESTAMP_NTZ(TIMESTAMP),

    ST_MAKEPOINT(
        TRY_TO_DOUBLE(LONGITUDE),
        TRY_TO_DOUBLE(LATITUDE)
    )

FROM GEOPULSE_DB.RAW.GPS_PINGS_LANDING

WHERE
    DEVICEID IS NOT NULL
    AND TRIM(DEVICEID) <> ''

    AND TRY_TO_DOUBLE(LATITUDE) BETWEEN -90 AND 90

    AND TRY_TO_DOUBLE(LONGITUDE) BETWEEN -180 AND 180

    AND TRY_TO_TIMESTAMP_NTZ(TIMESTAMP) IS NOT NULL;


INSERT INTO GEOPULSE_DB.RAW.GPS_PINGS
(
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    EVENT_TIMESTAMP,
    LOCATION
)

SELECT
    TRIM(DEVICEID),

    TRY_TO_DOUBLE(LATITUDE),

    TRY_TO_DOUBLE(LONGITUDE),

    TRY_TO_TIMESTAMP_NTZ(TIMESTAMP),

    ST_MAKEPOINT(
        TRY_TO_DOUBLE(LONGITUDE),
        TRY_TO_DOUBLE(LATITUDE)
    )

FROM GEOPULSE_DB.RAW.GPS_PINGS_LANDING

WHERE
    DEVICEID IS NOT NULL
    AND TRIM(DEVICEID) <> ''

    AND TRY_TO_DOUBLE(LATITUDE) BETWEEN -90 AND 90

    AND TRY_TO_DOUBLE(LONGITUDE) BETWEEN -180 AND 180

    AND TRY_TO_TIMESTAMP_NTZ(TIMESTAMP) IS NOT NULL;


SELECT COUNT(*) AS TOTAL_GPS_RECORDS
FROM GEOPULSE_DB.RAW.GPS_PINGS;


SELECT
    COUNT(DISTINCT DEVICE_ID) AS UNIQUE_DEVICES
FROM GEOPULSE_DB.RAW.GPS_PINGS;

//Check geographic points
SELECT
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    EVENT_TIMESTAMP,
    ST_ASWKT(LOCATION) AS GEO_POINT
FROM GEOPULSE_DB.RAW.GPS_PINGS
LIMIT 10;

//Check missing values


SELECT
    COUNT_IF(DEVICE_ID IS NULL) AS MISSING_DEVICE,
    COUNT_IF(LATITUDE IS NULL) AS MISSING_LATITUDE,
    COUNT_IF(LONGITUDE IS NULL) AS MISSING_LONGITUDE,
    COUNT_IF(EVENT_TIMESTAMP IS NULL) AS MISSING_TIMESTAMP,
    COUNT_IF(LOCATION IS NULL) AS MISSING_LOCATION
FROM GEOPULSE_DB.RAW.GPS_PINGS;

//Check duplicate records


SELECT
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    EVENT_TIMESTAMP,
    COUNT(*) AS DUPLICATE_COUNT
FROM GEOPULSE_DB.RAW.GPS_PINGS
GROUP BY
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    EVENT_TIMESTAMP
HAVING COUNT(*) > 1
LIMIT 20;

//Check geographical boundaries


SELECT
    MIN(LATITUDE) AS MIN_LATITUDE,
    MAX(LATITUDE) AS MAX_LATITUDE,
    MIN(LONGITUDE) AS MIN_LONGITUDE,
    MAX(LONGITUDE) AS MAX_LONGITUDE,
    MIN(EVENT_TIMESTAMP) AS FIRST_PING,
    MAX(EVENT_TIMESTAMP) AS LAST_PING
FROM GEOPULSE_DB.RAW.GPS_PINGS;


SELECT
    (SELECT COUNT(*)
     FROM GEOPULSE_DB.RAW.GPS_PINGS_LANDING)
        AS LANDING_RECORDS,

    (SELECT COUNT(*)
     FROM GEOPULSE_DB.RAW.GPS_PINGS)
        AS FINAL_GPS_RECORDS,

    (SELECT COUNT(DISTINCT DEVICE_ID)
     FROM GEOPULSE_DB.RAW.GPS_PINGS)
        AS UNIQUE_DEVICES;




















