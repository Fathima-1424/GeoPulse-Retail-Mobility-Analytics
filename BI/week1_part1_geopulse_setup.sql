CREATE TABLE IF NOT EXISTS GPS_PINGS_LANDING (
    DEVICEID VARCHAR(100),
    LATITUDE VARCHAR(50),
    LONGITUDE VARCHAR(50),
    TIMESTAMP VARCHAR(50)
);


CREATE TABLE IF NOT EXISTS GPS_PINGS (
    DEVICE_ID VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    EVENT_TIMESTAMP TIMESTAMP_NTZ,
    LOCATION GEOGRAPHY,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


CREATE OR REPLACE FILE FORMAT GPS_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('NULL', '');


CREATE OR REPLACE STAGE GPS_STAGE
    FILE_FORMAT = GPS_CSV_FORMAT;



LIST @GEOPULSE_DB.RAW.GPS_STAGE;


COPY INTO GEOPULSE_DB.RAW.GPS_PINGS_LANDING
FROM @GEOPULSE_DB.RAW.GPS_STAGE
FILES = ('geopulse_cleaned_pings.csv')
FILE_FORMAT = (
    FORMAT_NAME = 'GEOPULSE_DB.RAW.GPS_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';


SELECT
